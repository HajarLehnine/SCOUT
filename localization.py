def translate(text, language="English", **values):
	"""Translate a known interface string; preserve unknown text verbatim."""
	try:
		index = LANGUAGES.index(language)
	except ValueError:
		index = 0
	template = _TRANSLATIONS.get(text, (text,) * len(LANGUAGES))[index]
	return template.format(**values) if values else template


